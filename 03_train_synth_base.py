"""
03_train_synth_base.py

Train a decoder-only Transformer for symbolic pop-melody generation.

This script loads training settings from a YAML config file and trains either:
  - a synthetic-pretrained LM from scratch
  - a model initialized from a pretrained checkpoint
  - a resumed run from a previous training checkpoint

Inputs:
  - --config: YAML config specifying dataset paths and training hyperparameters.
    The config typically points to `meta.jsonl` generated by 02_preprocess_synthetic_data.py.

Outputs:
  - Checkpoints and logs under `out_dir` (e.g., best.pt).

Example:
  python 03_train_synth_base.py --config configs/train_synth_base.yaml
    
Author:      <ludy>
Modified:    2026/06/12
Licence:     <MIT>
"""
import os
import math
import time
import torch
import random
import argparse
import yaml
import numpy as np
from torch.utils.data import DataLoader
from torch.optim import AdamW
from torch.utils.tensorboard import SummaryWriter

from model.tokenizer import REMITokenizer
from model.dataset import MelodyEventsDataset, MixedMelodyEventsDataset, collate_batch
from model.model import GPTMelody, weighted_token_ce_loss


def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)

def train(path_meta_jsonl, 
          out_dir, 
          max_len, 
          batch_size, 
          lr, 
          epochs, 
          seed,
          device,
          pretrained_ckpt=None,
          resume_ckpt=None,
          grad_accum_steps=1,
          replay_meta_jsonl=None,
          replay_ratio=0.0):
    """ train """
    grad_accum_steps = int(grad_accum_steps)
    if grad_accum_steps < 1:
        raise ValueError("grad_accum_steps must be >= 1")
    set_seed(seed)
    
    # out dir
    os.makedirs(out_dir, exist_ok=True)

    # Init tokenizer
    tokenizer = REMITokenizer()
    print(f"> Tokenizer initialized with vocab size: {len(tokenizer)}")

    # Create dataset
    print(f"> Creating datasets...")

    if replay_meta_jsonl and float(replay_ratio) > 0:
        ds_train = MixedMelodyEventsDataset(
            path_meta_jsonl,
            replay_meta_jsonl,
            max_len,
            "train",
            replay_ratio=replay_ratio,
            seed=seed,
        )
    else:
        ds_train = MelodyEventsDataset(path_meta_jsonl, max_len, "train")
    ds_eval = MelodyEventsDataset(path_meta_jsonl, max_len, "eval")
    n_over_max = ds_train.n_over_max_len + ds_eval.n_over_max_len
    max_observed_len = max(ds_train.max_observed_len, ds_eval.max_observed_len)
    if n_over_max > 0:
        raise ValueError(
            f"Dataset contains {n_over_max} train/eval sequence(s) longer than max_len={max_len}; "
            f"observed max={max_observed_len}. Increase max_len to preserve song endings."
        )

    dl_train = DataLoader(ds_train, batch_size=batch_size, shuffle=True,
                    collate_fn=lambda b: collate_batch(b, pad_id=tokenizer.pad_id()),
                    num_workers=2, pin_memory=True)
    dl_eval = DataLoader(ds_eval, batch_size=batch_size, shuffle=True,
                    collate_fn=lambda b: collate_batch(b, pad_id=tokenizer.pad_id()),
                    num_workers=2, pin_memory=True)
    print(f">     - Train set: {len(ds_train)}")
    if isinstance(ds_train, MixedMelodyEventsDataset):
        print(f">       - Primary train samples: {ds_train.n_primary}")
        print(f">       - Replay train samples: {ds_train.n_replay}")
        print(f">       - Replay ratio: {ds_train.replay_ratio:g}")
    print(f">     - Eval set: {len(ds_eval)}")
    print(f">     - Maximum token length: {max_observed_len}")
    print(f">     - Micro batch size: {batch_size}")
    print(f">     - Gradient accumulation: {grad_accum_steps}")
    print(f">     - Effective batch size: {batch_size * grad_accum_steps}")

    # create model
    print(f"> Creating model...")
    model = GPTMelody(vocab_size=len(tokenizer), 
                        d_model=512, 
                        n_head=8, 
                        n_layer=6, 
                        max_len=max_len).to(device)
    opt = AdamW(model.parameters(), lr=lr, betas=(0.9, 0.95), weight_decay=0.1)

    start_epoch = 1
    step = 0
    best_val = 1e9

    if pretrained_ckpt and resume_ckpt:
        raise ValueError("Error: use only one of pretrained_ckpt or resume_ckpt.")
    if pretrained_ckpt:
        load_model_weights(pretrained_ckpt, model, tokenizer, max_len, device)
        print(f"> Initialized model from pretrained checkpoint: {pretrained_ckpt}")
    if resume_ckpt:
        resume_state = load_training_checkpoint(resume_ckpt, model, opt, tokenizer, max_len, device)
        start_epoch = int(resume_state.get("epoch", 0)) + 1
        step = int(resume_state.get("step", 0))
        best_val = float(resume_state.get("best_val", 1e9))
        print(f"> Resumed training from checkpoint: {resume_ckpt}")
        print(f">     - start_epoch={start_epoch}, step={step}, best_val={best_val:.4f}")

    # warmup + cosine [For demo]
    optimizer_steps_per_epoch = math.ceil(len(dl_train) / grad_accum_steps)
    total_steps = epochs * optimizer_steps_per_epoch
    warmup = max(100, int(0.03 * total_steps))

    def lr_at(step):
        if step < warmup:
            return lr * (step + 1) / warmup
        t = (step - warmup) / max(1, total_steps - warmup)
        return lr * 0.5 * (1 + math.cos(math.pi * t))

    # tensorboard
    run_name = time.strftime("%Y%m%d-%H%M%S")
    writer = SummaryWriter(log_dir=os.path.join(out_dir, run_name))

    # Train loop: eval every epoch (and save best ckpt)
    ema_loss = None
    for ep in range(start_epoch, epochs + 1):
        ### Train ###
        model.train()
        opt.zero_grad(set_to_none=True)
        group_loss = 0.0
        for batch_idx, batch in enumerate(dl_train):
            x = batch["x"].to(device)
            y = batch["y"].to(device)
            attn = batch["attn"].to(device)
            w = batch["weight"].to(device)

            logits = model(x, attn_mask=attn)
            loss = weighted_token_ce_loss(logits, y, attn_mask=attn, sample_weight=w)
            group_start = (batch_idx // grad_accum_steps) * grad_accum_steps
            group_size = min(grad_accum_steps, len(dl_train) - group_start)
            (loss / group_size).backward()
            group_loss += float(loss.item())

            update_now = (batch_idx + 1) % grad_accum_steps == 0 or batch_idx + 1 == len(dl_train)
            if update_now:
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)

                lr_now = lr_at(step)
                for pg in opt.param_groups:
                    pg["lr"] = lr_now
                opt.step()
                opt.zero_grad(set_to_none=True)

                l = group_loss / group_size
                group_loss = 0.0
                ema_loss = l if ema_loss is None else 0.98 * ema_loss + 0.02 * l

                if step % 200 == 0:
                    print(f"ep={ep} step={step} loss={l:.4f} lr={opt.param_groups[0]['lr']:.2e} "
                          f"w_mean={w.mean().item():.3f} w_min={w.min().item():.3f} w_max={w.max().item():.3f}")
                    writer.add_scalar("train/loss", l, step)
                    writer.add_scalar("train/loss_ema", ema_loss, step)
                    writer.add_scalar("train/lr", lr_now, step)
                    writer.add_scalar("train/w_mean", float(w.mean().item()), step)
                    writer.add_scalar("train/w_min", float(w.min().item()), step)
                    writer.add_scalar("train/w_max", float(w.max().item()), step)
                step += 1

        ### Eval ###
        loss_eval = eval_epoch(model, dl_eval, device)

        # tensorboard
        writer.add_scalar("eval/loss", loss_eval, ep)
        print(f"ep={ep} eval loss={loss_eval:.4f}")

        # Save ckpt every epoch
        path_ckpt = os.path.join(out_dir, f"gpt_melody_ep{ep}.pt")
        save_ckpt(path_ckpt, model, tokenizer, max_len, opt, ep, step, best_val)
        print(f"> [Epoch {ep}] Checkpoint saved to {path_ckpt}")
        # best checkpoint
        if loss_eval < best_val:
            best_val = loss_eval
            path_ckpt = os.path.join(out_dir, f"best.pt")
            save_ckpt(path_ckpt, model, tokenizer, max_len, opt, ep, step, best_val)
            print(f"> [Epoch {ep}] best.pt saved to {path_ckpt}")

@torch.no_grad()
def eval_epoch(model, loader, device):
    model.eval()
    total_loss, n_batches = 0.0, 0
    for batch in loader:
        x = batch["x"].to(device)
        y = batch["y"].to(device)
        attn = batch["attn"].to(device)
        w = batch["weight"].to(device)

        logits = model(x, attn_mask=attn)
        loss = weighted_token_ce_loss(logits, y, attn_mask=attn, sample_weight=w)

        total_loss += float(loss.item())
        n_batches += 1
    loss_eval = total_loss / max(1, n_batches)
    return loss_eval

def check_ckpt_compatible(ckpt, tokenizer, max_len, path_ckpt):
    vocab = ckpt.get("vocab")
    if vocab is not None and list(vocab) != list(tokenizer.id_to_token):
        raise ValueError(f"Error: checkpoint vocab is incompatible with current tokenizer: {path_ckpt}")

    ckpt_max_len = int(ckpt.get("config", {}).get("max_len", max_len))
    if ckpt_max_len != max_len:
        raise ValueError(f"Error: checkpoint max_len={ckpt_max_len}, but current max_len={max_len}: {path_ckpt}")

def load_model_weights(path_ckpt, model, tokenizer, max_len, device):
    ckpt = torch.load(path_ckpt, map_location=device)
    check_ckpt_compatible(ckpt, tokenizer, max_len, path_ckpt)
    model.load_state_dict(ckpt["model"])
    return ckpt

def load_training_checkpoint(path_ckpt, model, opt, tokenizer, max_len, device):
    ckpt = load_model_weights(path_ckpt, model, tokenizer, max_len, device)
    if "optimizer" in ckpt:
        opt.load_state_dict(ckpt["optimizer"])
    else:
        print("> Warning: checkpoint has no optimizer state; resumed model weights with a fresh optimizer.")
    return ckpt

def save_ckpt(path_ckpt, model, tokenizer, max_len, opt=None, epoch=None, step=None, best_val=None):
    ckpt = {"model": model.state_dict(),
            "vocab": tokenizer.id_to_token,
            "config": {"max_len": max_len}
           }
    if opt is not None:
        ckpt["optimizer"] = opt.state_dict()
    if epoch is not None:
        ckpt["epoch"] = epoch
    if step is not None:
        ckpt["step"] = step
    if best_val is not None:
        ckpt["best_val"] = best_val
    torch.save(ckpt, path_ckpt)



def load_config(path_yaml):
    with open(path_yaml, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    if not isinstance(data, dict):
        raise ValueError(f"Error: YAML root must be a mapping/dict: {path_yaml}")
    return data

def resolve_device(device_name=None):
    if device_name is None:
        return "cuda" if torch.cuda.is_available() else "cpu"
    device_name = str(device_name)
    if device_name.startswith("cuda") and not torch.cuda.is_available():
        print("> Warning: CUDA requested but unavailable; using CPU.")
        return "cpu"
    return device_name

def parse_args(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--config", type=str, default="configs/train_synth_base.yaml")
    p.add_argument("--pretrained_ckpt", type=str, default=None,
                   help="Initialize model weights from a pretrained checkpoint, e.g. for finetuning.")
    p.add_argument("--resume_ckpt", type=str, default=None,
                   help="Resume a previous training run. Loads model and optimizer state when available.")
    p.add_argument("--out_dir", type=str, default=None,
                   help="Override out_dir from config.")
    p.add_argument("--epochs", type=int, default=None,
                   help="Override total epochs from config.")
    p.add_argument("--lr", type=float, default=None,
                   help="Override learning rate from config.")
    p.add_argument("--batch_size", type=int, default=None,
                   help="Override batch size from config.")
    p.add_argument("--grad_accum_steps", type=int, default=None,
                   help="Accumulate this many micro-batches before each optimizer step.")
    p.add_argument("--replay_path_meta", type=str, default=None,
                   help="Optional replay meta.jsonl mixed into the train split.")
    p.add_argument("--replay_ratio", type=float, default=None,
                   help="Replay samples per primary train sample, e.g. 1.0 for 1:1.")
    p.add_argument("--device", type=str, default=None,
                   help="Override device from config.")
    return p.parse_args(argv)

def main(argv=None):
    args = parse_args(argv)
    cfg = load_config(args.config)

    # param
    path_meta = cfg["path_meta"]
    out_dir = args.out_dir or cfg["out_dir"]

    max_len = int(cfg.get("max_len", 1200))
    batch_size = int(args.batch_size if args.batch_size is not None else cfg.get("batch_size", 16))
    grad_accum_steps = int(
        args.grad_accum_steps if args.grad_accum_steps is not None
        else cfg.get("grad_accum_steps", 1)
    )
    lr = float(args.lr if args.lr is not None else cfg.get("lr", 3e-4))
    epochs = int(args.epochs if args.epochs is not None else cfg.get("epochs", 20))
    seed = int(cfg.get("seed", 47))
    device = resolve_device(args.device if args.device is not None else cfg.get("device"))
    pretrained_ckpt = args.pretrained_ckpt or cfg.get("pretrained_ckpt")
    resume_ckpt = args.resume_ckpt or cfg.get("resume_ckpt")
    replay_meta = args.replay_path_meta or cfg.get("replay_path_meta")
    replay_ratio = float(
        args.replay_ratio if args.replay_ratio is not None
        else cfg.get("replay_ratio", 0.0)
    )

    # train
    train(path_meta, out_dir, max_len, batch_size, lr, 
          epochs, seed, device, pretrained_ckpt, resume_ckpt, grad_accum_steps,
          replay_meta_jsonl=replay_meta, replay_ratio=replay_ratio)

# =========================
# Main
# =========================
if __name__ == "__main__":
    main()
